import { expect, test } from '@playwright/test';
const aspects = ['Kejujuran', 'Keberanian', 'Kesopanan', 'Kebijaksanaan', 'Keadilan'];
test('teacher preview shows school roster and the separate twelve-point observation form', async ({ page }, testInfo) => {
    await page.setViewportSize({ width: 1280, height: 1100 });
    await page.goto('/guru/?mockMonitoring=1');
    await page.getByLabel('Username', { exact: true }).fill('guru.demo');
    await page.getByLabel('Password', { exact: true }).fill('local-test-only');
    await page.getByRole('button', { name: 'Masuk ke monitoring' }).click();
    await expect(page.getByRole('heading', { name: 'Pilih siswa yang diamati' })).toBeVisible();
    await expect(page.getByLabel('Siswa di sekolah Anda').locator('option')).toHaveCount(1);
    await page.getByRole('button', { name: 'Isi pengamatan siswa' }).click();
    await expect(page.getByLabel('Nama guru pengamat')).toBeVisible();
    await expect(page.getByRole('spinbutton', { name: 'Periode monitoring', exact: true })).toHaveValue('1');
    await page.getByLabel('Periode monitoring').press('ArrowUp');
    await expect(page.getByLabel('Periode monitoring')).toHaveValue('2');
    await page.getByLabel('Periode monitoring').press('ArrowDown');
    await expect(page.getByLabel('Titik observasi', { exact: true }).locator('option')).toHaveCount(12);
    for (const aspect of aspects) await expect(page.getByLabel(aspect, { exact: true })).toBeVisible();
    await expect(page.getByLabel('Penguatan / arahan guru (opsional)')).toBeVisible();
    await page.screenshot({ path: testInfo.outputPath('teacher-form-desktop.png'), fullPage: true });
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: testInfo.outputPath('teacher-form-mobile.png'), fullPage: true });
});

test('separate parent and teacher observations reach scoped admin charts and explain forward-chaining results', async ({ page }) => {
    await page.goto('/form/?mockMonitoring=1');
    await page.getByLabel('Username', { exact: true }).fill('arjuna.pratama'); await page.getByLabel('Password', { exact: true }).fill('local-test-only');
    await page.getByRole('button', { name: 'Masuk ke monitoring' }).click();
    for (let point = 1; point <= 6; point++) {
        await page.getByLabel('Nama orang tua / wali').fill('Wali Arjuna');
        await page.getByLabel('Titik observasi', { exact: true }).selectOption(String(point));
        await page.getByLabel('Tanggal dan waktu observasi').fill('2026-10-17T08:00');
        await page.getByLabel('Situasi yang diamati').fill('Pengamatan rumah titik ' + point);
        for (const aspect of aspects) await page.getByLabel(aspect, { exact: true }).selectOption(aspect === 'Keberanian' ? 'na' : '4');
        await page.getByRole('button', { name: 'Simpan catatan', exact: true }).click();
        await expect(page.locator('.parent-status[role="status"]')).toContainText('Catatan titik ' + point + ' berhasil disimpan');
    }
    await page.getByRole('button', { name: 'Keluar', exact: true }).click();
    await page.goto('/guru/?mockMonitoring=1');
    await page.getByLabel('Username', { exact: true }).fill('guru.demo'); await page.getByLabel('Password', { exact: true }).fill('local-test-only');
    await page.getByRole('button', { name: 'Masuk ke monitoring' }).click();
    await expect(page.getByLabel('Siswa di sekolah Anda').locator('option')).toHaveCount(1);
    await page.getByRole('button', { name: 'Isi pengamatan siswa' }).click();
    await expect(page.locator('.parent-progress')).toContainText('0 dari 12 titik sudah memiliki catatan.');
    for (let point = 1; point <= 6; point++) {
        await page.getByLabel('Nama guru pengamat').fill('Guru Arjuna');
        await page.getByLabel('Titik observasi', { exact: true }).selectOption(String(point));
        await page.getByLabel('Tanggal dan waktu observasi').fill('2026-10-18T13:00');
        await page.getByLabel('Situasi yang diamati').fill('Pengamatan sekolah titik ' + point);
        for (const aspect of aspects) await page.getByLabel(aspect, { exact: true }).selectOption(aspect === 'Keberanian' ? 'na' : point <= 3 ? '2' : '4');
        await page.getByRole('button', { name: 'Simpan catatan', exact: true }).click();
        await expect(page.locator('.parent-status[role="status"]')).toContainText('Catatan titik ' + point + ' berhasil disimpan');
    }
    await expect(page.getByRole('heading', { name: 'Riwayat monitoring (6 catatan)' })).toBeVisible();
    await page.setViewportSize({ width: 390, height: 844 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: test.info().outputPath('teacher-monitoring-phone.png'), fullPage: true });
    await page.setViewportSize({ width: 1366, height: 1200 });
    await page.goto('/admin/?mockAdmin=1');
    await page.getByLabel('Nama pengguna').fill('admin.demo'); await page.getByLabel('Password', { exact: true }).fill('local-test-only');
    await page.getByRole('button', { name: 'Masuk ke panel' }).click();
    await page.getByRole('tab', { name: 'Monitoring', exact: true }).click();
    await expect(page.locator('.dashboard-tab-panel [data-reporter="parent"]')).toContainText('1 dari 56 siswa');
    await expect(page.locator('.dashboard-tab-panel [data-reporter="teacher"]')).toContainText('1 dari 56 siswa');
    await page.getByRole('tab', { name: 'Siswa', exact: true }).click();
    await page.getByRole('button', { name: 'Monitoring @arjuna.pratama', exact: true }).click();
    const dialog = page.getByRole('dialog', { name: 'Monitoring siswa', exact: true });
    await expect(dialog.locator('.monitoring-history')).toHaveCount(2);
    await expect(dialog.locator('.monitoring-history').nth(0)).toContainText('6 catatan');
    await expect(dialog.locator('.monitoring-history').nth(1)).toContainText('6 catatan');
    const honesty = dialog.locator('.comparison-card').filter({ has: page.getByRole('heading', { name: 'Kejujuran', exact: true }) });
    await expect(honesty).toContainText('Perlu klarifikasi'); await expect(honesty).toContainText('6/12 titik berpasangan');
    await honesty.getByText('Lihat penalaran dan selisih 12 titik').click();
    await expect(honesty).toContainText('R3: minimal 3 titik');
    await expect(dialog.locator('.comparison-card').filter({ has: page.getByRole('heading', { name: 'Keberanian', exact: true }) })).toContainText('Data belum cukup');
    await dialog.locator('.monitoring-comparison').screenshot({ path: test.info().outputPath('forward-chaining-comparison.png') });
    await dialog.getByRole('button', { name: 'Tutup monitoring', exact: true }).click();
    await page.getByRole('tab', { name: 'Monitoring', exact: true }).click();
    await page.getByLabel('Periode monitoring', { exact: true }).fill('2');
    await page.getByRole('button', { name: 'Terapkan periode' }).click();
    await expect(page.locator('.dashboard-tab-panel [data-reporter="parent"]')).toContainText('0 dari 56 siswa');
    await expect(page.locator('.dashboard-tab-panel [data-reporter="teacher"]')).toContainText('0 dari 56 siswa');
    await page.getByRole('tab', { name: 'Siswa', exact: true }).click();
    await page.getByRole('button', { name: 'Monitoring @arjuna.pratama', exact: true }).click();
    await expect(page.getByRole('dialog', { name: 'Monitoring siswa', exact: true }).locator('.comparison-card').first()).toContainText('0/12 titik berpasangan');
    await page.goto('/form/?mockMonitoring=1');
    await page.getByRole('button', { name: 'Keluar akun guru' }).click();
    await page.getByLabel('Username', { exact: true }).fill('arjuna.pratama');
    await page.getByLabel('Password', { exact: true }).fill('local-test-only');
    await page.getByRole('button', { name: 'Masuk ke monitoring' }).click();
    await expect(page.getByRole('heading', { name: 'Riwayat monitoring (6 catatan)' })).toBeVisible();
});
